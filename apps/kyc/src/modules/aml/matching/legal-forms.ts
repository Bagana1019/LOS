// Хуулийн хэлбэрийн үгс (ХХК, LLC, Ltd …). ААН-ийн нэрийг харьцуулахад хоёр талаас хасна: Монголын компани бүртгэлд "ХХК/ХК",
// НҮБ-ын жагсаалтад "LLC/Ltd/Co" эсвэл огт байхгүй байж болно; үлдсэн токен бүр нэрийн оноог буруугаар бууруулдаг (FR-13.1).
// Жагсаалт зориудаар богино: нэрийн утга агуулсан үгс (Trading, Holdings, Bank …) энд ороогүй.
// 1-2 үсэгт нормчигдох хэлбэрүүд (S.A., B.V., N.V., AG) жинхэнэ токентой андуурагдах тул оруулаагүй. ООО/OOO нь 'o' болж
// нормчлогддог тул жагсаалтад биш, normalizeEntityName-д LLC болгож (орос хэлний ООО = LLC) хөрвүүлнэ.
import { normalizeName } from './normalize';

export const LEGAL_FORMS: readonly string[] = [
  // Монгол: хязгаарлагдмал хариуцлагатай компани, хувьцаат компани, төрийн өмчит үйлдвэрийн газар,
  // орон нутгийн өмчит аж ахуйн нэгж, банк бус санхүүгийн байгууллага
  'ХХК', 'ХК', 'ТӨҮГ', 'ОНӨААТҮГ', 'ББСБ',
  // Олон улсын
  'LLC', 'LLP', 'Ltd', 'Limited', 'Co', 'Company', 'Inc', 'Incorporated', 'Corp', 'Corporation',
  'JSC', 'OJSC', 'CJSC', 'PJSC', 'PLC', 'GmbH', 'FZE', 'FZC', 'FZCO', 'Pvt', 'SARL', 'SRL',
  // Орос: хаалттай ба нээлттэй хувьцаат компани
  'ЗАО', 'ОАО',
];

// Токенууд normalizeName-ээр нормчлогдсон тул (ХХК → "hk", LLC → "lc") жагсаалтыг мөн адил нормчилно.
const NORMALIZED_FORMS: ReadonlySet<string> = new Set(LEGAL_FORMS.map(normalizeName));

/** Нормчилсон токен нь хуулийн хэлбэр мөн эсэх. */
export function isLegalFormToken(token: string): boolean {
  return NORMALIZED_FORMS.has(token);
}

// Цэгтэй богино бичлэг: L.L.C., F.Z.E., P.J.S.C., S.A.R.L., Х.Х.К, "L. L. C." — нэг үсэг бүрийн хойно цэг. Токенчилол цэгийг зай болгож
// "l l c" гэсэн гурван токен болгодог тул нормчлохын ӨМНӨ цэгтэй үсгийн цувааг залгана. Үгийн дундаас эхлэхгүй (хил хязгаартай),
// дор хаяж 2 үсэгтэй, төгсгөлийн цэгийг хамруулна.
const DOTTED_RUN = /(?<![\p{L}\p{N}])\p{L}(?:\s*\.\s*\p{L})+(?:\s*\.)?(?![\p{L}\p{N}])/gu;
// ООО (кирилл о эсвэл латин o гурав) = LLC. Нэг үсэг болж нормчлогдохоос өмнө нь үгээр нь солино.
const RUSSIAN_LLC = /(?<![\p{L}\p{N}])[oо]{3}(?![\p{L}\p{N}])/giu;

/**
 * ААН-ийн нэрийг нормчлохоос өмнө хуулийн хэлбэрийг таних боломжтой болгоно: цэгтэй үсгийн цувааг залгана (L.L.C. → LLC,
 * Х.Х.К → ХХК), ООО/OOO-г LLC болгоно. Хувь хүний нэрэнд хэрэглэхгүй. Idempotent.
 */
export function normalizeEntityName(name: string): string {
  return name
    .normalize('NFKC')
    .replace(DOTTED_RUN, (run) => run.replace(/[\s.]/gu, ''))
    .replace(RUSSIAN_LLC, 'LLC');
}
