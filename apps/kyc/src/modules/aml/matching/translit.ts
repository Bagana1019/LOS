// Кирилл → латин. MNS 5217:2012-ийн хялбаршуулсан хувилбар (монгол + орос) дээр казах, украин, беларусь, серб, македон
// болон бусад кирилл бичгийн үсгийг нэмсэн: ямар ч кирилл үсэг латин руу орохгүй үлдэхгүй (кирилл-латин холимог токен
// үүсэхгүй). НҮБ-ын жагсаалтын латин бичиглэл диакритикгүй (ө→o, ү→u), тиймээс ө/ү-г o/u болгоно.
// Шийдвэр:
//  - ъ, ь унагана: дуугүй тэмдэг; ICAO Doc 9303 (Игорь→Igor, Ильяс→Ilyas) ба НҮБ-ын орос нэрийн латин бичиглэл ингэдэг.
//  - ы → y (Сүхбаатарын → Sukhbaataryn), й → i, е → e (word-initial "ye" болгохгүй: Сергей → Sergei), ё → yo.
//  - щ → shch (ICAO).
//  - Казах/татар/башкир/узбек/тажик: ә→a, ғ→g, қ→k, ң→n, ұ→u, һ→h, ҳ→h, ҷ→j, җ→j; украин: і→i, ї→yi, є→ye, ґ→g;
//    беларусь ў→u; серб/македон: ђ→dj, ћ→c, ј→j, љ→lj, њ→nj, џ→dz, ѕ→dz (ѓ, ќ нь суурь үсэг г, к рүү NFKD-ээр орно).
//  - Түүхэн/цөөн хэрэглэгддэг үсэг (ѣ ѳ ѵ …) нь хамгийн ойр дуудлагаар; ӏ (палочка) дуугүй тул унагана.
//  - Хүснэгтэд байхгүй үлдсэн ямар ч кирилл үсэг (Cyrillic Extended-B/C, Komi…) унана — хэзээ ч кирилл хэвээр үлдэхгүй.
// Зөвхөн жижиг үсгийн map: нэрийг өмнө нь lowercase хийсэн байх ёстой (normalizeName хийнэ).
const CYRILLIC_TO_LATIN: Readonly<Record<string, string | undefined>> = {
  // орос + монгол
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'j', з: 'z', и: 'i', й: 'i',
  к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', ө: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u',
  ү: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'shch', ъ: '', ы: 'y', ь: '', э: 'e',
  ю: 'yu', я: 'ya',
  // украин, беларусь, серб, македон
  і: 'i', ї: 'yi', є: 'ye', ґ: 'g', ў: 'u', ђ: 'dj', ћ: 'c', ј: 'j', љ: 'lj', њ: 'nj', џ: 'dz', ѕ: 'dz',
  // казах, татар, башкир, узбек, тажик, киргиз
  ә: 'a', ғ: 'g', қ: 'k', ң: 'n', ұ: 'u', һ: 'h', ҳ: 'h', ҷ: 'j', җ: 'j', ҙ: 'z', ҫ: 's', ҡ: 'k', ҥ: 'n', ӈ: 'n', ӣ: 'i', ӯ: 'u',
  // кавказ, абхаз, осет, чуваш, бусад
  ҕ: 'g', ҝ: 'k', ҟ: 'k', ҩ: 'o', ҧ: 'p', ҭ: 't', ҵ: 'ts', ҹ: 'ch', ҽ: 'ch', ҿ: 'ch', ӄ: 'q', ӆ: 'l', ӊ: 'n', ӌ: 'ch', ӎ: 'm',
  ӕ: 'ae', ӛ: 'e', ӡ: 'dz', ӷ: 'g', ӻ: 'g', ӽ: 'h', ӿ: 'h', ӏ: '',
  // түүхэн
  ѡ: 'o', ѣ: 'e', ѥ: 'ye', ѧ: 'ya', ѩ: 'ya', ѫ: 'u', ѭ: 'yu', ѯ: 'ks', ѱ: 'ps', ѳ: 'f', ѵ: 'i', ѷ: 'i', ѹ: 'u', ѻ: 'o', ѽ: 'o', ѿ: 'ot',
  ҋ: 'i', ҍ: '', ҏ: 'r', ҁ: '',
  // Komi
  ԁ: 'd', ԃ: 'dj', ԅ: 'zj', ԇ: 'dz', ԉ: 'lj', ԋ: 'nj', ԍ: 'g', ԏ: 'tj', ԑ: 'e', ԓ: 'l', ԕ: 'k', ԗ: 'q', ԙ: 'q', ԛ: 'q', ԝ: 'w',
};

const CYRILLIC_LETTER = /^[\p{Script=Cyrillic}]$/u;
// ө-г паспортын хэлбэрээр 'u' болгох нөхцөл (MNS 5217 паспорт: Ө → U). Хоёр хэлбэрийг normalizeNameForms харьцуулна.
const PASSPORT_OE = 'ө';

export interface TransliterateOptions {
  /** ө-г 'o' биш 'u' болгоно (Монгол паспортын латин бичиглэл: Өлзий → Ulzii). */
  oeAsU?: boolean;
}

export function transliterateCyrillic(lower: string, options: TransliterateOptions = {}): string {
  let out = '';
  for (const ch of lower) {
    // ASCII хурдан зам (нэрийн ихэнх тэмдэгт): хүснэгт, NFKD хэрэггүй.
    if (ch.charCodeAt(0) < 0x80) {
      out += ch;
      continue;
    }
    if (options.oeAsU && ch === PASSPORT_OE) {
      out += 'u';
      continue;
    }
    const mapped = CYRILLIC_TO_LATIN[ch];
    if (mapped !== undefined) {
      out += mapped;
    } else if (CYRILLIC_LETTER.test(ch)) {
      // Диакритиктай кирилл (жнь ѓ ќ ѐ) нь суурь үсгээрээ орно; хүснэгтэд байхгүй үлдсэн кирилл үсэг/тэмдэг унана.
      out += CYRILLIC_TO_LATIN[ch.normalize('NFKD')[0]] ?? '';
    } else {
      out += ch; // латин (диакритиктай ч), бусад бичиг: хэвээр
    }
  }
  return out;
}
