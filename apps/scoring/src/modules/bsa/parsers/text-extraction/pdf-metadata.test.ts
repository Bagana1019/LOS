import { describe, expect, it } from 'vitest';
import { parsePdfDate, pdfInfoString } from './pdf-metadata';

describe('parsePdfDate', () => {
  it.each([
    ["D:20260301102030Z", '2026-03-01T10:20:30.000Z'],
    ["D:20260301102030", '2026-03-01T10:20:30.000Z'], // бүс байхгүй → UTC гэж таамаглана
    ["D:20260301102030+08'00'", '2026-03-01T02:20:30.000Z'],
    ["D:20260301102030-05'30'", '2026-03-01T15:50:30.000Z'],
    ["D:20260301102030+08'00", '2026-03-01T02:20:30.000Z'], // төгсгөлийн ' байхгүй
    ['D:20260301102030+0800', '2026-03-01T02:20:30.000Z'],
    ['D:20260301102030+08', '2026-03-01T02:20:30.000Z'],
    ["D:20260301102030Z00'00'", '2026-03-01T10:20:30.000Z'],
    ['D:202603011020', '2026-03-01T10:20:00.000Z'], // секундгүй
    ['D:20260301', '2026-03-01T00:00:00.000Z'],
    ['D:202603', '2026-03-01T00:00:00.000Z'],
    ['D:2026', '2026-01-01T00:00:00.000Z'],
    ['20260301102030Z', '2026-03-01T10:20:30.000Z'], // "D:" угтваргүй
    ['2026-03-01T10:20:30+08:00', '2026-03-01T02:20:30.000Z'], // зарим үүсгэгч ISO бичдэг
    ["  D:20260301102030Z  ", '2026-03-01T10:20:30.000Z'],
  ])('%s → %s', (raw, iso) => {
    expect(parsePdfDate(raw)).toBe(iso);
  });

  it('өдөр өөрчлөгдөх бүсийн шилжилт (өмнөх өдөр рүү)', () => {
    expect(parsePdfDate("D:20260101003000+08'00'")).toBe('2025-12-31T16:30:00.000Z');
  });

  it.each([
    'D:20261301000000Z', // 13-р сар
    'D:20260230000000Z', // 2-р сарын 30
    'D:20260301250000Z', // 25 цаг
    'D:20260301106000Z', // 60 минут
    'D:00000101000000Z', // жил 0
    "D:20260301102030+25'00'", // бүсийн цаг > 23
    'D:2026030110203', // сондгой урт
    'garbage',
    '',
    '   ',
    'D:',
  ])('буруу огноо %j → null', (raw) => {
    expect(parsePdfDate(raw)).toBeNull();
  });

  it.each([undefined, null, 20260301, {}, []])('мөр биш %j → null', (raw) => {
    expect(parsePdfDate(raw)).toBeNull();
  });
});

describe('pdfInfoString', () => {
  it('trim хийж, хоосон бол null, мөр биш бол null', () => {
    expect(pdfInfoString('  Microsoft Word  ')).toBe('Microsoft Word');
    expect(pdfInfoString('   ')).toBeNull();
    expect(pdfInfoString('')).toBeNull();
    expect(pdfInfoString(undefined)).toBeNull();
    expect(pdfInfoString(42)).toBeNull();
  });

  it('удирдлагын тэмдэгтийг зай болгож, уртыг 256 хүртэл хязгаарлана', () => {
    expect(pdfInfoString('a\u0000b\nc')).toBe('a b c');
    expect(pdfInfoString('x'.repeat(1000))).toHaveLength(256);
  });
});
