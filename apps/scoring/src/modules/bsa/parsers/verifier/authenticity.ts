// PDF metadata-аар хуурамч эсэхийг эвристикээр шалгах (BSA-FR-2.3). Баталгаа БИШ — зөвхөн анхааруулга: producer/creator нь засварлагч,
// оффис, онлайн PDF хэрэгслийн тэмдэгтэй таарвал, эсвэл зассан огноо үүсгэсэн огнооноос хол хойно бол. Шифрлэлт/гарын үсгийг тайлагнана.
import type { AuthenticityReport, StatementFileMeta, VerificationIssue } from '../statement.types';
import { VERIFY_DEFAULTS } from './verify-defaults';

export interface AuthenticityOptions {
  suspiciousProducerSignatures: readonly string[];
  pdfModifiedToleranceSeconds: number;
}

export interface AuthenticityResult {
  report: AuthenticityReport;
  /** Түвшин тавигдаагүй (WARNING-аар) issue-ууд; verifier түвшинг options-оор тохируулна */
  issues: VerificationIssue[];
}

/** Жижиг үсэг, үсэг-цифрээс бусдыг хассан (Microsoft® Word → 'microsoftword') */
const squash = (s: string): string => s.normalize('NFKD').toLowerCase().replace(/[^a-z0-9]+/g, '');

const EMPTY_REPORT: AuthenticityReport = {
  checked: false,
  producer: null,
  creator: null,
  suspiciousSignatures: [],
  modifiedAfterSeconds: null,
  isEncrypted: false,
  hasSignature: false,
};

function seconds(iso: string | null): number | null {
  if (!iso) return null;
  const t = Date.parse(iso);
  return Number.isFinite(t) ? t / 1000 : null;
}

export function checkAuthenticity(
  meta: StatementFileMeta,
  options: Partial<AuthenticityOptions> = {},
): AuthenticityResult {
  const pdf = meta.pdf;
  if (!pdf) return { report: { ...EMPTY_REPORT }, issues: [] };
  const signatures = options.suspiciousProducerSignatures ?? VERIFY_DEFAULTS.suspiciousProducerSignatures;
  const tolerance = options.pdfModifiedToleranceSeconds ?? VERIFY_DEFAULTS.pdfModifiedToleranceSeconds;

  const haystacks = [pdf.producer, pdf.creator].filter((x): x is string => !!x).map(squash);
  const matched = signatures.filter((sig) => {
    const needle = squash(sig);
    return needle !== '' && haystacks.some((h) => h.includes(needle));
  });

  const created = seconds(pdf.creationDate);
  const modified = seconds(pdf.modDate);
  const modifiedAfterSeconds = created !== null && modified !== null ? Math.round(modified - created) : null;

  const report: AuthenticityReport = {
    checked: true,
    producer: pdf.producer,
    creator: pdf.creator,
    suspiciousSignatures: matched,
    modifiedAfterSeconds,
    isEncrypted: pdf.isEncrypted,
    hasSignature: pdf.hasSignature,
  };

  const issues: VerificationIssue[] = [];
  if (matched.length > 0) {
    issues.push({
      code: 'PDF_METADATA_SUSPICIOUS',
      severity: 'WARNING',
      message: `PDF producer/creator matches an editing or office tool (${matched.join(', ')}); bank statements are normally generated by the bank's system`,
    });
  }
  if (modifiedAfterSeconds !== null && modifiedAfterSeconds > tolerance) {
    issues.push({
      code: 'PDF_MODIFIED',
      severity: 'WARNING',
      message: `PDF was modified ${modifiedAfterSeconds} s after it was created (tolerance ${tolerance} s)`,
    });
  }
  return { report, issues };
}
